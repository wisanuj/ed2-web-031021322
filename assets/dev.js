/* dev.js — real-device photo cards: photo with numbered markers, what it does, legend, IEC symbol and terminal numbers.
   Data: devdata.js (generated by Docs/make_devices.py). Needs shell.js (MC.t), ed.js (ED.tt), ch2.js (C2.symSVG) and lesson.js (LS.zoom).
   DEV.mount(el, ids) draws the cards for the device ids into el. */
const DEV = {};
DEV.byId = id => (window.DEVDATA || []).find(d => d.id === id);
DEV.credit = im => {
  const T = MC.t;
  if (!im.credit) return im.note ? ED.tt(im.note) : '';
  const c = im.credit, sa = /BY-SA/.test(c.lic);
  return T('ภาพ: ', 'photo: ') + `${c.artist} · <a href="${c.page}" target="_blank" rel="noopener">${c.title}</a> · Wikimedia Commons · ${c.lic}` +
    (c.mod ? T(` · ตัดขอบ${sa ? ' เผยแพร่ภายใต้ ' + c.lic + ' เดียวกัน' : ''}`, ` · cropped${sa ? ', shared under the same ' + c.lic : ''}`) : '');
};
DEV.card = d => {
  const T = MC.t, tt = ED.tt;
  const syms = (d.syms || []).map(id => (window.C2 && C2.SYMS) ? C2.SYMS.find(s => s.id === id) : null).filter(Boolean);
  const tabs = d.imgs.length > 1 ? `<div class="devtabs toggles" role="tablist">${d.imgs.map((im, k) => `<button type="button" class="btn${k ? '' : ' on'}" data-k="${k}">${tt((d.tabs || [])[k] || [`${k + 1}`, `${k + 1}`])}</button>`).join('')}</div>` : '';
  const figs = d.imgs.map((im, k) => `<figure class="devfig" data-k="${k}"${k ? ' hidden' : ''}><div class="devpic"${im.h > im.w * 1.2 ? ` style="max-width:${Math.round(460 * im.w / im.h)}px;margin:0 auto"` : ''}><img src="${im.src}" width="${im.w}" height="${im.h}" loading="lazy" decoding="async" alt="${tt(d.name)}">` +
    im.marks.map(([n, x, y]) => `<b class="mk" data-n="${n}" style="left:${x}%;top:${y}%">${n}</b>`).join('') + `</div><figcaption>${DEV.credit(im)}</figcaption></figure>`).join('');
  const legs = d.imgs.map((im, k) => { const ns = [...new Set(im.marks.map(m => m[0]))].sort((a, b) => a - b);
    return ns.length ? `<ol class="devleg" data-k="${k}"${k ? ' hidden' : ''}>${ns.map(n => `<li data-n="${n}"><b>${n}</b><span>${tt(d.leg[n - 1])}</span></li>`).join('')}</ol>` : ''; }).join('');
  return `<article class="devcard" id="dev-${d.id}"><div class="devhead"><span class="devcode">${d.code}</span><div><h3>${tt(d.name)}</h3>` +
    `<div class="deviec">${T('รหัสในวิชานี้', 'course code')} <b>${d.code}</b> · IEC 81346-2 <b>${d.iec}</b></div></div></div>` +
    tabs + figs + `<p class="devwhat">${tt(d.what)}</p>` + legs +
    `<div class="devsym">${syms.map(s => `<span class="ds">${C2.symSVG(s, 0.8)}<i>${tt(s.name)}</i></span>`).join('')}<p><b>${T('เลขขั้ว', 'terminals')}</b> ${tt(d.terms)}</p></div></article>`;
};
DEV.mount = (el, ids) => {
  el.innerHTML = `<div class="devgrid">${ids.map(id => DEV.byId(id)).filter(Boolean).map(DEV.card).join('')}</div>`;
  el.querySelectorAll('.devcard').forEach(card => {
    card.querySelectorAll('.devtabs button').forEach(b => b.addEventListener('click', () => {
      const k = b.dataset.k; card.querySelectorAll('.devtabs button').forEach(x => x.classList.toggle('on', x === b));
      card.querySelectorAll('.devfig, .devleg').forEach(x => { x.hidden = x.dataset.k !== k; }); }));
    const hl = (n, on) => card.querySelectorAll(`[data-n="${n}"]`).forEach(x => x.classList.toggle('hl', on));
    card.querySelectorAll('.mk, .devleg li').forEach(x => {
      x.addEventListener('pointerenter', () => hl(x.dataset.n, true)); x.addEventListener('pointerleave', () => hl(x.dataset.n, false));
      x.addEventListener('click', e => { e.stopPropagation(); const on = !x.classList.contains('hl'); card.querySelectorAll('.hl').forEach(y => y.classList.remove('hl')); if (on) hl(x.dataset.n, true); }); });
    card.querySelectorAll('.devpic img').forEach(img => img.addEventListener('click', () => window.LS && LS.zoom && LS.zoom(img)));
  });
};
